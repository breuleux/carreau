import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5317/?example=IDE");
const show = () => page.evaluate(() => { const f = (n) => (n.type === "pane" ? n.tabs.map((t) => (t.group ? `${t.title}{${f(t.group.children[0])}}` : t.title)).join("+") : `${n.type}(${n.children.map(f).join(", ")})`); const n = window.ws.node(window.ws.selection.id); return f(window.ws.root) + `  [sel ${n.type === "pane" ? n.tabs[n.active].title : n.type}]`; });
await page.locator(".carreau-tab", { hasText: /^Terminal$/ }).click();
await page.keyboard.down("Alt"); await page.keyboard.press("KeyQ"); await page.keyboard.press("KeyQ"); await page.keyboard.up("Alt");
await page.keyboard.press("KeyP");
console.log("before:            ", await show());
await page.keyboard.press("KeyG"); await page.keyboard.press("Escape");
console.log("G, Esc:            ", await show());
await page.keyboard.press("KeyG"); await page.locator(".carreau-tab-edit").fill(""); await page.keyboard.press("Enter");
console.log("G, empty, Enter:   ", await show());
await page.keyboard.press("Shift+KeyZ");
console.log("Shift+Z (nothing): ", await show());
await page.keyboard.press("KeyG"); await page.keyboard.type("Ok"); await page.keyboard.press("Enter");
console.log("G, Ok:             ", await show());
await page.keyboard.press("Shift+Digit5"); await page.keyboard.press("Escape");
console.log("%, Esc (keeps):    ", await show());
await page.keyboard.press("Shift+Digit5"); await page.locator(".carreau-tab-edit").fill(""); await page.keyboard.press("Enter");
console.log("%, empty (keeps):  ", await show());
await browser.close();
