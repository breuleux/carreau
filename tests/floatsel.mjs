import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 }, deviceScaleFactor: 2 });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5317/?example=IDE");
const accented = () => page.evaluate(() => [...document.querySelectorAll(".carreau-pane.selected .carreau-tab.active")].map((t) => `${t.textContent}${t.closest(".carreau-float") ? " (window)" : " (main)"}`).join(", ") || "none");
const outline = page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Outline$/ }) });
await outline.locator(".carreau-more").click();
await page.locator(".carreau-menu button", { hasText: "Float" }).click();
// split the window: drag Terminal onto the window's left third
const win = page.locator(".carreau-float");
const g = await page.locator(".carreau-root .carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Terminal$/ }) }).locator(".carreau-tabspace").boundingBox();
const w = await win.boundingBox();
await page.mouse.move(g.x + 5, g.y + 5); await page.mouse.down();
await page.mouse.move(g.x + 40, g.y - 40, { steps: 5 });
await page.mouse.move(w.x + w.width * 0.12, w.y + w.height * 0.5, { steps: 8 });
await page.mouse.up();
await page.locator(".carreau-tab", { hasText: /^main\.ts$/ }).click();
console.log("click main.ts:          ", await accented());
await win.locator(".carreau-tab", { hasText: /^Outline$/ }).click();
console.log("click Outline in window:", await accented());
await page.screenshot({ path: "/tmp/floatsel.png" });
await page.keyboard.down("Alt"); await page.keyboard.press("KeyQ"); await page.keyboard.press("KeyQ"); await page.keyboard.up("Alt");
await page.keyboard.press("ArrowLeft");
console.log("Alt+Left (in window):   ", await accented());
await page.keyboard.press("KeyP");
console.log("Alt+P: selection kind   ", await page.evaluate(() => window.ws.node(window.ws.selection.id)?.type), "| outline above window?", await page.evaluate(() => document.querySelector(".carreau-selection").classList.contains("in-float")));
await page.keyboard.press("KeyM");
console.log("Alt+M in window: maximized =", await page.evaluate(() => window.ws.maximized?.id ?? "-"));
await page.locator(".carreau-root .carreau-tab", { hasText: /^README\.md$/ }).click();
console.log("click README in main:   ", await accented());
await browser.close();
