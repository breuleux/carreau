import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
await page.goto("http://localhost:5317/?example=Embeds");
await page.waitForTimeout(2000);
const yt = page.frames().filter((f) => f.url().includes("youtube"));
console.log("youtube frames:", yt.length, yt.map((f) => f.url()).join(" "));
const grip = page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Big Buck Bunny$/ }) }).locator(".carreau-tabspace");
const g = await grip.boundingBox();
const host = await page.locator(".carreau-root").boundingBox();
await page.mouse.move(g.x + 5, g.y + 5); await page.mouse.down();
await page.mouse.move(g.x + 100, g.y + 200, { steps: 10 });
await page.mouse.move(host.x + host.width - 3, host.y + host.height / 2, { steps: 10 });
console.log("active:", await page.evaluate(() => window.view.drag?.active?.target.kind));
await page.mouse.up();
await page.waitForTimeout(500);
console.log("detached after pane move:", yt.map((f) => f.isDetached()).join(","));
console.log("layout:", await page.evaluate(() => window.ws.root.children.map((c) => c.type + (c.type === "pane" ? ":" + c.tabs[0].title : "")).join(" | ")));
await page.screenshot({ path: "/tmp/yt.png" });
await browser.close();
