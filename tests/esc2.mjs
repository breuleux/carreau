import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5317/?example=IDE");
const outline = page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Outline$/ }) });
await outline.locator(".carreau-more").click();
await page.locator(".carreau-menu button", { hasText: "Float" }).click();
const bar = await page.locator(".carreau-float-bar").boundingBox();
const st = () => page.evaluate(() => `docking=${!!window.view.drag} translucent=${!!document.querySelector(".carreau-float.docking")} x=${Math.round(window.ws.floating[0].rect.x)}`);
await page.mouse.move(bar.x + 20, bar.y + 5); await page.mouse.down();
await page.mouse.move(400, 300, { steps: 6 });
await page.waitForTimeout(1200);
console.log("held 1.2s:   ", await st());
await page.keyboard.press("Escape");
await page.mouse.move(420, 300, { steps: 3 });
console.log("Esc + move:  ", await st());
await page.mouse.move(300, 300, { steps: 6 });
await page.waitForTimeout(1200);
console.log("held again:  ", await st());
await page.mouse.up();
await browser.close();
