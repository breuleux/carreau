import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 }, deviceScaleFactor: 2 });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5317/?example=IDE");
const pane = page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Terminal$/ }) });
await pane.locator(".carreau-tabspace").click();
console.log("grip click -> menu?", await page.locator(".carreau-menu").count());
await pane.locator(".carreau-more").click();
console.log("dots click -> menu?", await page.locator(".carreau-menu").count());
const m = await page.locator(".carreau-menu").boundingBox(), d = await pane.locator(".carreau-more").boundingBox();
console.log("menu at", Math.round(m.x), Math.round(m.y), "dots at", Math.round(d.x), Math.round(d.y + d.height));
await page.screenshot({ path: "/tmp/menu.png", clip: { x: 160, y: 590, width: 300, height: 120 } });
await pane.locator(".carreau-more").click();
console.log("dots again -> menu?", await page.locator(".carreau-menu").count());
await pane.locator(".carreau-more").click();
await page.mouse.click(700, 300);
console.log("outside click -> menu?", await page.locator(".carreau-menu").count());
await pane.locator(".carreau-more").click();
await page.locator(".carreau-menu button", { hasText: "Float" }).click();
console.log("floats:", await page.evaluate(() => window.ws.floating.length), "| float has dots?", await page.locator(".carreau-float .carreau-more").count());
await browser.close();
