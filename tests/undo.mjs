import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5317/?example=Embeds");
await page.waitForTimeout(800);
const show = () => page.evaluate(() => { const f = (n) => (n.type === "pane" ? n.tabs.map((t) => t.title).join("+") : `${n.type}(${n.children.map(f).join(", ")})`); const n = window.ws.node(window.ws.selection.id); return `${f(window.ws.root)}  [sel ${n.type === "pane" ? n.tabs[n.active].title : n.type}]`; });
const counterTab = await page.evaluate(() => window.ws.root.children[0].children[1].tabs[0].id);
const counter = page.frameLocator(`.carreau-content[data-tab="${counterTab}"] iframe`);
await page.locator(".carreau-tab", { hasText: /^Counter A$/ }).click();
for (let i = 0; i < 3; i++) await counter.locator("#b").click();
console.log("start:   ", await show());
// drag the Counter A pane (header empty area) onto the left third of the video pane
const h = await page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Counter A$/ }) }).locator(".carreau-tabspace").boundingBox();
const v = await page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^Big Buck Bunny$/ }) }).boundingBox();
await page.mouse.move(h.x + 5, h.y + 5); await page.mouse.down();
await page.mouse.move(h.x + 40, h.y - 40, { steps: 5 });
await page.mouse.move(v.x + v.width * 0.15, v.y + v.height / 2, { steps: 8 });
await page.mouse.up();
console.log("dragged: ", await show());
await page.keyboard.down("Alt"); await page.keyboard.press("KeyQ"); await page.keyboard.press("KeyQ"); await page.keyboard.up("Alt");
await page.keyboard.press("ArrowRight");
console.log("→:       ", await show());
await page.keyboard.press("KeyZ");
console.log("Z:       ", await show());
await page.keyboard.press("KeyZ");
console.log("Z:       ", await show());
await page.keyboard.press("Shift+KeyZ");
console.log("Shift+Z: ", await show());
console.log("counter clicks (iframe kept):", await counter.locator("#n").textContent());
await browser.close();
