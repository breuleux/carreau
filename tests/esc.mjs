import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://localhost:5317/?example=IDE");
const st = () => page.evaluate(() => (window.view.drag ? `dragging, active=${window.view.drag.active?.target.kind ?? "none"}` : "no drag"));
const t = await page.locator(".carreau-tab", { hasText: /^Outline$/ }).boundingBox();
const m = await page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^main\.ts$/ }) }).boundingBox();
await page.mouse.move(t.x + 5, t.y + 5); await page.mouse.down();
await page.mouse.move(m.x + m.width * 0.85, m.y + m.height / 2, { steps: 8 });
console.log("before Esc:      ", await st());
await page.keyboard.press("Escape");
await page.mouse.move(m.x + m.width * 0.8, m.y + m.height / 2, { steps: 3 });
console.log("moved right after:", await st());
await page.waitForTimeout(300);
await page.mouse.move(m.x + m.width * 0.85, m.y + m.height / 2, { steps: 3 });
console.log("after 0.3s:      ", await st());
await page.waitForTimeout(300);
await page.mouse.move(m.x + m.width * 0.8, m.y + m.height / 2, { steps: 3 });
console.log("after 0.6s:      ", await st());
await page.keyboard.press("Escape");
await page.mouse.up();
console.log("released during cooldown: layout unchanged?", await page.evaluate(() => window.ws.root.children.length === 3));
await browser.close();
